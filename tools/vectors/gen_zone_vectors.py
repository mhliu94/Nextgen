#!/usr/bin/env python3
"""Generate tests/fixtures/zone_vectors.inc: TZif files plus reference conversions by CPython.

The C++ time zones read TZif files from the system tz database for zones other than the
built-in ones. The test embeds a few real TZif files (so it does not depend on the box's
tzdata) and checks offsets and wall-clock conversions against Python's zoneinfo, including
daylight-saving gaps and overlaps (fold=0) and instants far beyond the files' transition
tables, where the POSIX TZ footer applies.

    python3 -I tools/vectors/gen_zone_vectors.py > tests/fixtures/zone_vectors.inc
"""
from datetime import datetime, timedelta, timezone
import pathlib
import sys
from zoneinfo import ZoneInfo

ZONEINFO = pathlib.Path("/usr/share/zoneinfo")
# Northern and southern hemisphere DST, a half-hour fixed offset, and 45-minute offsets with DST.
ZONES = ["Europe/London", "Australia/Sydney", "Asia/Kolkata", "Pacific/Chatham"]
YEARS = [1975, 1996, 2026, 2037, 2040, 2100]


def offset(zone, epoch):
    return int(datetime.fromtimestamp(epoch, timezone.utc).astimezone(zone).utcoffset().total_seconds())


def transitions(zone, year):
    start = int(datetime(year, 1, 1, tzinfo=timezone.utc).timestamp())
    end = int(datetime(year + 1, 1, 1, tzinfo=timezone.utc).timestamp())
    found = []
    previous = offset(zone, start)
    for t in range(start + 3600, end + 1, 3600):
        current = offset(zone, t)
        if current != previous:
            lo, hi = t - 3600, t
            while hi - lo > 1:
                mid = (lo + hi) // 2
                if offset(zone, mid) == previous:
                    lo = mid
                else:
                    hi = mid
            found.append((hi, previous, current))
        previous = current
    return found


print("// Generated by tools/vectors/gen_zone_vectors.py; do not edit by hand.")
print("#include <cstddef>")
for name in ZONES:
    data = (ZONEINFO / name).read_bytes()
    ident = name.replace("/", "_")
    print(f"static const unsigned char kTzif_{ident}[] = {{")
    for i in range(0, len(data), 24):
        print("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    print("};")
print("static const struct { const char* name; const unsigned char* data; std::size_t size; } kTzifFiles[] = {")
for name in ZONES:
    ident = name.replace("/", "_")
    print(f'    {{"{name}", kTzif_{ident}, sizeof(kTzif_{ident})}},')
print("};")

offsets, locals_ = [], []
for name in ZONES:
    zone = ZoneInfo(name)
    for year in YEARS:
        for month in range(1, 13):
            for day in (1, 15):
                t = int(datetime(year, month, day, 12, tzinfo=timezone.utc).timestamp())
                offsets.append((name, t, offset(zone, t)))
        for t, before, after in transitions(zone, year):
            offsets.append((name, t - 1, before))
            offsets.append((name, t, after))
            # Wall-clock times inside the gap or overlap around the transition, and an ordinary one.
            local_before = datetime.fromtimestamp(t, timezone.utc) + timedelta(seconds=before)
            for minutes in (-90, 15, 30, abs(after - before) // 60 + 30):
                wall = (local_before + timedelta(minutes=minutes)).replace(tzinfo=None)
                epoch = datetime(wall.year, wall.month, wall.day, wall.hour, wall.minute, wall.second, tzinfo=zone).timestamp()
                locals_.append((name, wall, int(epoch)))

print("static const struct { const char* zone; long long epoch; int offset; } kZoneOffsets[] = {")
for name, t, off in offsets:
    print(f'    {{"{name}", {t}LL, {off}}},')
print("};")
print("static const struct { const char* zone; const char* date; int hour, minute, second; long long epoch; } kZoneLocalTimes[] = {")
for name, wall, epoch in locals_:
    print(f'    {{"{name}", "{wall:%Y-%m-%d}", {wall.hour}, {wall.minute}, {wall.second}, {epoch}LL}},')
print("};")
print(f"// {len(offsets)} offsets, {len(locals_)} wall-clock conversions", file=sys.stderr)
