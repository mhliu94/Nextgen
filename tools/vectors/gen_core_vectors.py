def cstr(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def random_decimal_text(max_digits=17, max_scale=8):
    digits = random.randint(1, max_digits)
    scale = random.randint(0, min(max_scale, digits + 3))
    mantissa = random.randint(0, 10**digits - 1)
    text = str(mantissa).rjust(scale + 1, "0")
    if scale:
        text = text[:-scale] + "." + text[-scale:]
    return ("-" if random.random() < 0.15 and mantissa else "") + text


